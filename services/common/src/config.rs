use std::collections::HashMap;
use std::time::Duration;

/// A secret string that is redacted in logs, debug output, and JSON.
///
/// Used for connection URLs and other secrets loaded from configuration. The
/// cleartext is only accessible through [`RedactedSecret::expose`], keeping
/// secrets out of structured log lines and serialized responses.
#[derive(Clone, Default, PartialEq, Eq)]
pub struct RedactedSecret(String);

impl RedactedSecret {
    /// Wrap a secret value.
    pub fn new(value: impl Into<String>) -> Self {
        Self(value.into())
    }

    /// Expose the cleartext value to the caller.
    pub fn expose(&self) -> &str {
        &self.0
    }

    /// Consume the wrapper, returning the cleartext value.
    pub fn into_inner(self) -> String {
        self.0
    }
}

impl std::fmt::Debug for RedactedSecret {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "RedactedSecret([REDACTED])")
    }
}

impl std::fmt::Display for RedactedSecret {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "[REDACTED]")
    }
}

impl Serialize for RedactedSecret {
    fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        serializer.serialize_str("[REDACTED]")
    }
}

impl<'de> Deserialize<'de> for RedactedSecret {
    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        let value = String::deserialize(deserializer)?;
        Ok(Self(value))
    }
}

/// Root configuration structure loaded from TOML + environment.
#[derive(Debug, Clone, Default, Deserialize, Serialize)]
pub struct Config {
    #[serde(default)]
    pub service: ServiceConfig,
    #[serde(default)]
    pub server: ServerConfig,
    #[serde(default)]
    pub database: DatabaseConfig,
    #[serde(default)]
    pub redis: RedisConfig,
    #[serde(default)]
    pub auth: AuthConfig,
    #[serde(default)]
    pub tracing: TracingConfig,
    #[serde(default)]
    pub s3: S3Config,
    #[serde(default)]
    pub gateway: GatewayConfig,
    #[serde(default)]
    pub features: HashMap<String, bool>,
}

/// S3-compatible object storage configuration (MinIO in dev, AWS S3 in prod).
///
/// Documents are NEVER publicly accessible: all GET access goes through a
/// short-lived presigned URL generated by the workforce service after RBAC
/// and IDOR checks pass. The bucket must be created with no public policy.
#[derive(Debug, Clone, Deserialize, Serialize)]
pub struct S3Config {
    pub endpoint: String,
    pub region: String,
    pub bucket: String,
    pub access_key_id: RedactedSecret,
    pub secret_access_key: RedactedSecret,
    /// Presigned URL TTL in seconds. Keep short — 60s is the default.
    pub presign_ttl_secs: u64,
    /// Use path-style addressing (required for MinIO; AWS prefers virtual-hosted).
    pub force_path_style: bool,
}

impl Default for S3Config {
    fn default() -> Self {
        Self {
            endpoint: "http://localhost:9000".to_string(),
            region: "us-east-1".to_string(),
            bucket: "nexora-workforce-documents".to_string(),
            access_key_id: RedactedSecret::new("minioadmin"),
            secret_access_key: RedactedSecret::new("minioadmin"),
            presign_ttl_secs: 60,
            force_path_style: true,
        }
    }
}

/// Service identification and metadata.
#[derive(Debug, Clone, Deserialize, Serialize)]
pub struct ServiceConfig {
    pub name: String,
    pub version: String,
    pub environment: Environment,
    /// Auto-generated per-process ULID; omit from config files.
    #[serde(default = "crate::ulid::new_ulid")]
    pub instance_id: String,
}

impl Default for ServiceConfig {
    fn default() -> Self {
        Self {
            name: "nexora-service".to_string(),
            version: env!("CARGO_PKG_VERSION").to_string(),
            environment: Environment::Development,
            instance_id: crate::ulid::new_ulid(),
        }
    }
}

/// Deployment environment.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize, Serialize, Default)]
#[serde(rename_all = "lowercase")]
pub enum Environment {
    #[default]
    Development,
    Staging,
    Production,
}

impl Environment {
    pub fn is_production(&self) -> bool {
        matches!(self, Environment::Production)
    }
}

